from __future__ import annotations

from dataclasses import dataclass


@dataclass
class MNC:
    name: str
    careers_url: str
    delhi_ncr_office: str = ""  # "Gurugram", "Noida", "Delhi", etc. — informational only, never a location fallback
    # Listing URL for the company's open roles. Any ?q=/keywords= search param is a
    # legacy volume hint: the primary fetch strips it and pulls the FULL listing,
    # then filters title + location locally (services/title_filter, location_filter).
    # The un-stripped URL is reused only as a supplementary "net" on huge portals.
    pm_search_url: str = ""
    notes: str = ""
    api_url: str = ""      # explicit JSON endpoint when it cannot be derived from pm_search_url
    # ATS override. "" ⇒ auto-detect from the URL (mnc_careers/ats/detect.py);
    # one of mnc_careers.ats.TYPED ⇒ use that typed fetcher; "html" ⇒ force the
    # Playwright HTML lane (e.g. Akamai-fronted SuccessFactors tenants).
    api_type: str = ""
    hq_country: str = ""   # HQ / qualifying parent country (from the MNC input CSV)

    @property
    def ats_type(self) -> str:
        """Effective ATS: explicit override or detection from the listing/API URL."""
        if self.api_type:
            return self.api_type
        from mnc_careers.ats.detect import detect_ats  # local import: keep registry import light

        return detect_ats(self.api_url or self.pm_search_url)


def platform_for(mnc: MNC) -> str:
    """Job.platform for an MNC — the exact historical formula. Job.id depends on it: DO NOT CHANGE."""
    return f"mnc_{mnc.name.lower().replace(' ', '_').replace('/', '_')}"


